import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const schema = JSON.parse(
  fs.readFileSync(path.join(root, 'native/protocol-schema.json'), 'utf8')
);
const entries = (values, indent = '  ') =>
  Object.entries(values)
    .map(([name, value]) => `${indent}${name}: ${value},`)
    .join('\n');
const rustEntries = (values) => entries(values).replaceAll(':', ' =');

function tsEnum(name, values) {
  return `export const ${name} = {\n${entries(values)}\n} as const;\n\nexport type ${name} = (typeof ${name})[keyof typeof ${name}];`;
}

function rustEnum(name, values, repr = 'u8') {
  return `protocol_enum!(${name}: ${repr} {\n${rustEntries(values)}\n});`;
}

const ts = `// Generated by scripts/generate-native-protocol.js. Do not edit.\n\nexport const PROTOCOL_MAGIC = ${schema.magic};\nexport const PROTOCOL_VERSION = ${schema.version};\n\n${tsEnum('Opcode', schema.opcodes)}\n\n${tsEnum('StyleState', schema.styleStates)}\n\n${tsEnum('ElementKind', schema.elementKinds)}\n\n${tsEnum('ValueKind', schema.valueKinds)}\n\n${tsEnum('PropertyId', schema.properties)}\n\n${tsEnum('NativeEventId', schema.nativeEvents)}\n`;

const rust = `// Generated by scripts/generate-native-protocol.js. Do not edit.\n#![allow(dead_code)]\n\nmacro_rules! protocol_enum {\n    ($name:ident: $repr:ty { $($variant:ident = $value:expr,)* }) => {\n        #[derive(Clone, Copy, Debug, Eq, Hash, PartialEq, serde::Serialize)]\n        #[repr($repr)]\n        pub enum $name { $($variant = $value,)* }\n\n        impl TryFrom<$repr> for $name {\n            type Error = ();\n\n            fn try_from(value: $repr) -> Result<Self, ()> {\n                match value { $($value => Ok(Self::$variant),)* _ => Err(()) }\n            }\n        }\n    };\n}\n\npub const PROTOCOL_MAGIC: u32 = ${schema.magic};\npub const PROTOCOL_VERSION: u16 = ${schema.version};\n\n${rustEnum('Opcode', schema.opcodes)}\n${rustEnum('StyleState', schema.styleStates)}\n${rustEnum('ElementKind', schema.elementKinds)}\n${rustEnum('ValueKind', schema.valueKinds)}\n${rustEnum('PropertyId', schema.properties, 'u16')}\n${rustEnum('NativeEventId', schema.nativeEvents, 'u16')}\n`;

const outputs = [
  ['source/native/protocol.generated.ts', ts],
  ['native/src/protocol_generated.rs', rust],
];

let stale = false;
for (const [relativePath, content] of outputs) {
  const outputPath = path.join(root, relativePath);
  if (process.argv.includes('--check')) {
    if (
      !fs.existsSync(outputPath) ||
      fs.readFileSync(outputPath, 'utf8') !== content
    ) {
      console.error(`Generated protocol file is stale: ${relativePath}`);
      stale = true;
    }
  } else {
    fs.mkdirSync(path.dirname(outputPath), { recursive: true });
    // Only write when the content changed: unconditional writes bump mtimes
    // and force downstream rebuilds (cargo recompiles the native crate,
    // ~15 minutes) on every invocation.
    if (
      !fs.existsSync(outputPath) ||
      fs.readFileSync(outputPath, 'utf8') !== content
    ) {
      fs.writeFileSync(outputPath, content);
    }
  }
}
if (stale) process.exit(1);
